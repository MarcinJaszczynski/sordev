<h3>Polityka RODO</h3>
<p>
    Administratorem danych osobowych jest Biuro Podróży RAFA. Dane podane w formularzu umowy są
    przetwarzane wyłącznie w celu realizacji rezerwacji i wykonania umowy udziału w imprezie turystycznej.
</p>
<p>
    Dane mogą być przekazywane wyłącznie podmiotom niezbędnym do realizacji usługi (np. ubezpieczyciel,
    przewoźnik, hotel) oraz podmiotom uprawnionym na podstawie przepisów prawa.
</p>
<p>
    Masz prawo dostępu do swoich danych, ich sprostowania, ograniczenia przetwarzania, usunięcia,
    wniesienia sprzeciwu oraz złożenia skargi do Prezesa UODO.
</p>
